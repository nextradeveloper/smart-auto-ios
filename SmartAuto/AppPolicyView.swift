import SwiftUI

struct PolicySection: Identifiable {
    let title: String
    let text: String
    var id: String { title }

    init(_ title: String, _ text: String) {
        self.title = title
        self.text = text
    }
}

/// The same offline documents are available before login and from the account tab.
